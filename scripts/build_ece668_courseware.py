"""Build the courseware download and web handouts from one tracked source tree."""

import hashlib
import json
from pathlib import Path
import zipfile


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "_courseware" / "ece668"
PAGES = ROOT / "pages" / "teaching" / "ece-668" / "labs"
DOWNLOAD = ROOT / "assets" / "downloads" / "ece668-network-intelligence-lab.zip"


def main():
    files = sorted(path for path in SOURCE.rglob("*") if path.is_file()
                   and not any(part in {"__pycache__", "runs", ".venv", ".git"} for part in path.relative_to(SOURCE).parts)
                   and path.name != ".DS_Store" and path.suffix not in {".pyc", ".pyo"})
    manifest = {"version": "0.1.0", "files": {str(path.relative_to(SOURCE)): hashlib.sha256(path.read_bytes()).hexdigest() for path in files}}
    DOWNLOAD.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(DOWNLOAD, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, payload in [(str(path.relative_to(SOURCE)), path.read_bytes()) for path in files] + [
                ("package-manifest.json", (json.dumps(manifest, indent=2, sort_keys=True)+"\n").encode())]:
            info = zipfile.ZipInfo("ece668-network-intelligence-lab/"+name, date_time=(2026, 10, 27, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, payload)
    documents = [(f"project{i}", SOURCE / "docs" / f"project{i}.md") for i in range(1, 5)]
    documents += [("report-template", SOURCE / "docs" / "report-template.md"),
                  ("instructor-guide", SOURCE / "docs" / "instructor-guide.md"),
                  ("references", SOURCE / "REFERENCES.md")]
    PAGES.mkdir(parents=True, exist_ok=True)
    for slug, source in documents:
        title, body = source.read_text().split("\n", 1)
        title = title.lstrip("# ")
        frontmatter = "\n".join(["---", "layout: default", f"title: {json.dumps(title)}",
            f"header_title: {json.dumps(title)}", "subtitle: ECE 668 · Network Intelligence Lab · v0.1.0",
            "include_header: page_header.html", "nav_item: Teaching", f"permalink: /teaching/ece-668/labs/{slug}/", "---", ""])
        navigation = '<p><a href="/teaching/ece-668/labs/">← Project library</a> · <a href="/assets/downloads/ece668-network-intelligence-lab.zip">Download the complete package</a></p>\n'
        content = frontmatter + '<!-- Generated by scripts/build_ece668_courseware.py; edit the source handout. -->\n'
        content += navigation + '<div class="course-syllabus-content" markdown="1">\n' + body + '\n</div>\n'
        (PAGES / f"{slug}.md").write_text(content)
    print(f"Packaged {len(files)} source files; generated {len(documents)} handout pages; archive {DOWNLOAD.stat().st_size} bytes")


if __name__ == "__main__":
    main()
